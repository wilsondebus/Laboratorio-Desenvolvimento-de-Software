    private void carregarProfessores() {

        Conexao c = new Conexao();

        try (Connection conn = c.getConexao()) {

            if (conn == null) {
                JOptionPane.showMessageDialog(this, "Erro na conexão!");
                return;
            }

            ProfessoresDAO pDAO = new ProfessoresDAO(conn);

            professores = pDAO.listarProfessoresDAO();

            cmbProfessores.removeAllItems();

            for (Professores p : professores) {
                cmbProfessores.addItem(p);
            }

            cmbProfessores.setSelectedIndex(-1);

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao carregar professores: " + ex.getMessage());
        }
    }
    
