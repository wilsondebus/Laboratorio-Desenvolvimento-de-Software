    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        int idDisciplina = Integer.parseInt(txtConsultarID.getText());
        
        Conexao c = new Conexao(); 
        Connection conn = c.getConexao();
        
        DisciplinaDAO dDAO = new DisciplinaDAO(conn); 
        
        Disciplina d = dDAO.getDisciplina(idDisciplina); 
        
        if(d == null){
            limparFormulario();
            JOptionPane.showMessageDialog(this, "Disciplina não encontrada");
        } else {
            txtConsultarID.setText(idDisciplina + "");
            txtCargaHoraria.setText(d.getCargaHoraria());
            txtNome.setText(d.getNome());
            txtId.setText(d.getId()+"");
            
            cmbProfessores.setSelectedIndex(-1);
            
            for(int i = 0; i < cmbProfessores.getItemCount(); i++){
                Professores p = (Professores) cmbProfessores.getItemAt(i);
                
                if(p.getId() == d.getIdProfessor()){
                    cmbProfessores.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        // TODO add your handling code here:
        Conexao c = new Conexao();
        Connection conn = c.getConexao();
        
        if(conn == null){
            JOptionPane.showMessageDialog(this, "Erro ao conectar ao banco");
            return;
        }
        
        Disciplina d = new Disciplina();
        d.setId(Integer.parseInt(txtId.getText()));
        d.setNome(txtNome.getText());
        d.setCargaHoraria(txtCargaHoraria.getText());
        
        Professores p = professores.get(cmbProfessores.getSelectedIndex());
        d.setIdProfessor(p.getId());
        
        DisciplinaDAO dDAO = new DisciplinaDAO(conn);
        dDAO.editarDisciplina(d);
        
        limparFormulario();
    }//GEN-LAST:event_btnAtualizarActionPerformed

