    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        Conexao c = new Conexao(); 
        Connection conn = c.getConexao(); 
        c.getConexao();
        
        int idAluno = Integer.parseInt(txtConsultarId.getText());
        AlunoDAO aDAO = new AlunoDAO(c, conn); 
        
        Aluno aluno = aDAO.getAluno(idAluno);
        if(aluno == null){
            JOptionPane.showMessageDialog(this, "Pessoa não encontrada");
        } else {
            txtId.setText(aluno.getId()+"");
            txtNome.setText(aluno.getNome());
            txtIdade.setText(aluno.getIdade()+""); 
            cmbCurso.setSelectedItem(aluno.getCurso()); 
            
        }
        
    }//GEN-LAST:event_btnConsultarActionPerformed

