    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // Salvar disciplina e associar o professor selecionado 
        Professores p = (Professores) cmbProfessores.getSelectedItem(); 
        
        Disciplina d = new Disciplina(); 
        d.setNome(txtNomeDisciplina.getText());
        d.setCargaHoraria(txtCargaHoraria.getText());
        d.setIdProfessor(p.getId());
        
        Conexao c = new Conexao(); 
        Connection conn = c.getConexao();
        
        DisciplinaDAO dDAO = new DisciplinaDAO(conn);
        dDAO.inserirDisciplina(d);
        limparFormulario();   
    }//GEN-LAST:event_btnSalvarActionPerformed

