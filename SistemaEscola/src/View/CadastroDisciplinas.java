    private List<Professores> professores = new ArrayList<>(); 
    
    public void carregarProfessores(){
        Conexao c = new Conexao(); 
        
        try(Connection conn = c.getConexao()){
            if(conn == null){
                JOptionPane.showMessageDialog(this, "Erro na Conexão");
                return ;
            }
            
            ProfessoresDAO pDAO = new ProfessoresDAO(conn); 
            
            professores = pDAO.listarProfessoresDAO();
            
            cmbProfessores.removeAllItems(); 
            
            for(Professores p : professores){
                cmbProfessores.addItem(p);
            }
        } catch (SQLException ex){
            System.out.println("Erro ao carregar professores "+ex.getMessage());
        }
        
    }
    
    public void limparFormulario(){
        txtNomeDisciplina.setText("");
        txtCargaHoraria.setText("");
        cmbProfessores.setSelectedIndex(0); 
    }
    
