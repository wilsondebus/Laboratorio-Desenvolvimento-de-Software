    private void carregarAlunos(){
        DefaultTableModel modelo = (DefaultTableModel) tblAlunos.getModel();
        
        modelo.setColumnIdentifiers(new Object[]{"ID", "Nome", "Idade", "Curso"});
        
        modelo.setRowCount(0);
        
        Conexao c = new Conexao(); 
        
        try(Connection conn = c.getConexao()){
            
            if(conn == null){
                JOptionPane.showMessageDialog(this, "Erro ao conectar Banco");
                
                return ;
            }
            
            AlunoDAO dao = new AlunoDAO(c, conn); 
            
            List<Aluno> alunos = dao.listarAlunos();
            
            for(Aluno a : alunos){
                modelo.addRow(new Object[]{
                    a.getId(),
                    a.getNome(),
                    a.getIdade(),
                    a.getCurso()
                });
            }  
        } catch (SQLException ex){
            JOptionPane.showMessageDialog(this, "Erro ao carregar alunos: "+ex.getMessage());
        }
    }

