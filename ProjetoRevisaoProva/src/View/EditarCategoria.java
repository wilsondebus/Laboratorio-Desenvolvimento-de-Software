    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        CategoriasDAO cDAO = new CategoriasDAO();
        
        Categorias c = cDAO.getCategoria(Integer.parseInt(txtBuscarId.getText()));
        
        if(c != null){
            txtNome.setText(c.getNome());
        } else {
            txtNome.setText("");
            JOptionPane.showMessageDialog(null, "Categoria não encontrada!");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        // TODO add your handling code here:
        Categorias c = new Categorias();
        
        c.setId(Integer.parseInt(txtBuscarId.getText()));
        c.setNome(txtNome.getText());
        
        CategoriasDAO cDAO = new CategoriasDAO();
        
        cDAO.editar(c);
        
        JOptionPane.showMessageDialog(null, "Categoria atualizada!");
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        CategoriasDAO cDAO = new CategoriasDAO();
        
        cDAO.excluir(Integer.parseInt(txtBuscarId.getText()));
        
        JOptionPane.showMessageDialog(null, "Categoria excluída!");
        
        txtBuscarId.setText("");
        txtNome.setText("");
    }//GEN-LAST:event_btnExcluirActionPerformed

