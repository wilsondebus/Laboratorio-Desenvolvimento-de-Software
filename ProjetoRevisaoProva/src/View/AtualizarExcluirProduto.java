    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // Buscar ID
        ProdutoDAO pDAO = new ProdutoDAO();

        Produto p = pDAO.getProduto(Integer.parseInt(txtBuscarId.getText()));

        if (p != null) {

            txtNome.setText(p.getNome());
            txtPreco.setText(String.valueOf(p.getPreco()));
            txtQuantidade.setText(String.valueOf(p.getQuantidade()));

            for (int i = 0; i < cmbCategoria.getItemCount(); i++) {

                Categorias c = (Categorias) cmbCategoria.getItemAt(i);

                if (c.getId() == p.getCategoriaId()) {
                    cmbCategoria.setSelectedIndex(i);
                    break;
                }
            }

        } else {
            JOptionPane.showMessageDialog(null, "Produto não encontrado!");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        // TODO add your handling code here:
        Produto p = new Produto();
        
        p.setId(Integer.parseInt(txtBuscarId.getText()));
        p.setNome(txtNome.getText());
        p.setPreco(Double.parseDouble(txtPreco.getText()));
        p.setQuantidade(Integer.parseInt(txtQuantidade.getText()));
        
        Categorias c = (Categorias) cmbCategoria.getSelectedItem();
        
        p.setCategoriaId(c.getId());
        
        ProdutoDAO pDAO = new ProdutoDAO();
        
        pDAO.editar(p);
        
        JOptionPane.showMessageDialog(null, "Produto Atualizado");
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        ProdutoDAO pDAO = new ProdutoDAO();
        
        pDAO.remover(Integer.parseInt(txtBuscarId.getText()));
        
        
        JOptionPane.showMessageDialog(null, "Produto excluído");
        
        txtBuscarId.setText("");
        txtNome.setText("");
        txtPreco.setText("");
        txtQuantidade.setText("");
    }//GEN-LAST:event_btnExcluirActionPerformed

