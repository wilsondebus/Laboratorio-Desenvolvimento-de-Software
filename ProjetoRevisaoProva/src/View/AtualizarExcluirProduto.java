    public void carregarCategorias(){
        CategoriasDAO cDAO = new CategoriasDAO();

        List<Categorias> lista = cDAO.getCategorias();

        cmbCategoria.removeAllItems();

        if (lista != null) {
            for (Categorias c : lista) {
                cmbCategoria.addItem(c);
            }
        }
    }
    
