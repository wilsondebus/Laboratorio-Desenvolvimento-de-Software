    private void bntIgualActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntIgualActionPerformed
        // TODO add your handling code here:
        double resultado;
        n2 = Double.parseDouble(txtResultado.getText());
        if(operacao == "soma"){
            resultado = n1 + n2;
            lblValor.setText(n1 +" + "+ n2+ " = ");
            txtResultado.setText(String.valueOf(resultado)); 
        } else if (operacao == "multiplicacao"){
            resultado = n1 * n2; 
            lblValor.setText(n1 +" x "+n2+" = "); 
            txtResultado.setText(String.valueOf(resultado));
        } else if (operacao == "divisao"){
            resultado = n1 / n2;
            lblValor.setText(n1 + " / "+n2+ " = ");
            txtResultado.setText(String.valueOf(resultado)); 
        } else if (operacao == "subtracao"){
            resultado = n1 - n2; 
            lblValor.setText(n1 + " - "+n2+ " = ");
            txtResultado.setText(String.valueOf(resultado)); 
        }      
    }//GEN-LAST:event_bntIgualActionPerformed

