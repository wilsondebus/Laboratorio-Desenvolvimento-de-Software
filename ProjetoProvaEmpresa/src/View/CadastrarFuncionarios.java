    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        // TODO add your handling code here:
        Funcionarios f = new Funcionarios(); 

        f.setNome(txtNome.getText());
        f.setIdade(Integer.parseInt(txtIdade.getText())); 
        f.setSalario(Double.parseDouble(txtSalario.getText()));
        f.setCargo(cmbCargo.getSelectedItem()+""); 
        
        if(rbtnMasculino.isSelected()){
             genero = "Masculino"; 
             f.setGenero(genero);
        } else if(rbtnFeminino.isSelected()){
            genero = "Feminino";
            f.setGenero(genero);
        } else if(rbtnOutro.isSelected()){
            genero = "Outro"; 
            f.setGenero(genero);
        } else {
            JOptionPane.showMessageDialog(null, "Selecione um sexo", "Erro", JOptionPane.ERROR_MESSAGE); 
        }
        
        FuncionariosDAO fDAO = new FuncionariosDAO();
        fDAO.inserir(f);
        
        JOptionPane.showMessageDialog(null, "Funcionario Cadastrado");
        
    }//GEN-LAST:event_btnCadastrarActionPerformed

