    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        Pessoa pessoa = new Pessoa();
        
        String sexo;
        
        if(cmbSexo.getSelectedItem().toString().equals("Masculino")){
            sexo = "Masculino";
        } else if(cmbSexo.getSelectedItem().toString().equals("Feminino")){
            sexo = "Feminino";
        } else {
            sexo = "Outro"; 
        }
        
        try (Socket socket = new Socket("localhost", 12345)) {

            // Criar os canais de comunicação
            ObjectOutputStream saida =
                new ObjectOutputStream(socket.getOutputStream());

            ObjectInputStream entrada =
                    new ObjectInputStream(socket.getInputStream());

            // Enviar objeto Pessoa para o servidor
            saida.writeObject(pessoa);
            saida.flush();

            // Receber resposta do servidor
            String mensagem = (String) entrada.readObject();

            // Mostrar mensagem recebida
            JOptionPane.showMessageDialog(null, mensagem);

        } catch (Exception ex) {

            JOptionPane.showMessageDialog(null,
                    "Erro ao conectar com o servidor: " + ex.getMessage());
        }     
    }//GEN-LAST:event_btnSalvarActionPerformed

